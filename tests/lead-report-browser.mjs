import assert from 'node:assert/strict'
import { mkdir,readFile } from 'node:fs/promises'
import { join,extname } from 'node:path'
import { chromium } from '@playwright/test'

export async function leadReportBrowser(h,{ana,ben,unknown,ownerId,campaign,intro,membership}) {
  const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH,args:['--use-mock-keychain','--password-store=basic',...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? ['--no-sandbox'] : [])]})
  const proofDir=process.env.STRAP_LEAD_REPORT_PROOF_DIR ?? process.env.STRAP_PROOF_DIR ?? 'logs/proof/leads'
  await mkdir(proofDir,{recursive:true})
  try {for(const width of [1440,390]) {
    const context=await browser.newContext({viewport:{width,height:1000}})
    await context.route(h.origin+'/**',async route=>{
      const path=new URL(route.request().url()).pathname
      if(!path.includes('..')&&/\.(css|svg|woff2|png|ico)$/.test(path)) return route.fulfill({body:await readFile(join(process.cwd(),'public',path)),contentType:{'.css':'text/css','.svg':'image/svg+xml','.woff2':'font/woff2','.png':'image/png','.ico':'image/x-icon'}[extname(path)]})
      return route.continue()
    })
    const split=h.owner.indexOf('=');await context.addCookies([{name:h.owner.slice(0,split),value:h.owner.slice(split+1),url:h.origin}])
    const page=await context.newPage()
    const shot=async state=>{assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);assert.equal(await page.locator('section').filter({has:page.getByRole('heading',{name:'Inquiry and attendance funnel',exact:true})}).locator('table').evaluateAll(tables=>tables.every(table=>table.getBoundingClientRect().right<=table.closest('section').getBoundingClientRect().right)),true,'RPT-005: report tables stay inside their panel');await page.screenshot({path:join(proofDir,`RPT-005-${state}-${width}.png`),fullPage:true})}
    await page.goto(h.origin+'/app/leads')
    const funnel=page.locator('section').filter({has:page.getByRole('heading',{name:'Inquiry and attendance funnel',exact:true})})
    await funnel.getByText('Unknown source',{exact:true}).first().waitFor()
    const campaignRow=page.locator(`[data-funnel-campaign="${campaign.id}"]`)
    await campaignRow.locator('[data-campaign-cost]').getByText('$45.00',{exact:true}).waitFor()
    await campaignRow.locator('[data-campaign-revenue]').getByText('$130.00',{exact:true}).waitFor()
    await page.locator(`[data-funnel-member="${ben.id}"]`).getByText('Intro lapsed without native conversion',{exact:true}).waitFor()
    await shot('sources')
    await funnel.screenshot({path:join(proofDir,`RPT-005-funnel-panel-${width}.png`)})
    await campaignRow.screenshot({path:join(proofDir,`RPT-005-campaign-panel-${width}.png`)})
    await campaignRow.getByRole('link',{name:'Drill into campaign members and sales',exact:true}).click()
    assert.equal(await page.locator('[data-funnel-member]').count(),2)
    await page.locator(`[data-funnel-member="${ben.id}"]`).getByText('1 intro purchases · No native conversion',{exact:true}).waitFor()
    await shot('campaign')
    await page.getByRole('link',{name:'Clear campaign filter',exact:true}).click()
    await page.getByLabel('Acquisition source',{exact:true}).fill('Community event')
    await page.getByRole('button',{name:'Filter funnel',exact:true}).click()
    assert.equal(await page.locator('[data-funnel-member]').count(),1)
    const row=page.locator(`[data-funnel-member="${ana.id}"]`)
    await row.getByText('2 attended · repeat attendance',{exact:true}).waitFor()
    await row.getByText('1 intro purchases · Native membership converted',{exact:true}).waitFor()
    await row.getByText('$110.00 gross invoiced revenue',{exact:true}).waitFor()
    await row.getByText('Recorded sales evidence',{exact:true}).click()
    assert.equal(await row.locator('[data-intro-sale-id]').count(),1)
    assert.equal(await row.locator('[data-revenue-id]').count(),2)
    await shot('filtered')
    const openSales=async()=>{if(await row.locator('details').getAttribute('open') === null) await row.getByText('Recorded sales evidence',{exact:true}).click()}
    const native=await h.state()
    const sale=native.intros.sales.find(s=>s.personId===ana.id)
    await row.getByRole('link',{name:'Intro purchase',exact:true}).click()
    await page.locator(`[id="pack-${sale.packId}"]`).waitFor()
    await page.goBack()
    for(const [i,charge] of native.charges.filter(c=>[sale.packId,membership.id].includes(c.packId)).entries()) {
      await openSales()
      await row.getByRole('link',{name:'Original sale charge',exact:true}).nth(i).click()
      const receipt=page.locator(`[id="receipt-${charge.packId}"]`)
      assert.equal(await receipt.getAttribute('data-pack-id'),charge.packId)
      assert.equal(await receipt.locator('time').getAttribute('datetime'),native.packs.find(p=>p.id===charge.packId).createdAt)
      await receipt.getByText('$'+(charge.amountCents/100).toFixed(2),{exact:true}).first().waitFor()
      await page.goBack()
    }
    await openSales()
    await row.getByRole('link',{name:'Native membership',exact:true}).click()
    const pack=page.locator(`[id="pack-${membership.id}"]`)
    await pack.waitFor()
    await pack.locator(':scope > summary').click()
    await pack.getByText('Unlimited visits',{exact:false}).first().waitFor()
    await shot('membership-evidence')
    await page.goBack()
    await row.getByRole('link',{name:'Visit 1',exact:true}).click()
    await page.locator('#roster').waitFor()
    assert.ok((await page.locator('#roster').innerText()).includes(ana.name))
    await page.goBack()
    await row.getByRole('link',{name:'Inquiry 1',exact:true}).click()
    await page.locator('#lead').waitFor()
    assert.ok((await page.locator('#lead').innerText()).includes('EXTERNAL-PRIYA'))
    await shot('source-history')
    await page.getByLabel('Acquisition source',{exact:true}).fill('No such source')
    await page.getByRole('button',{name:'Filter funnel',exact:true}).click()
    assert.equal(await page.locator('[data-funnel-member]').count(),0)
    await shot('empty')
    const add=page.locator('form[action*="name=lead.create"]')
    await add.getByLabel('Person',{exact:true}).selectOption(unknown.personId)
    await add.getByLabel('Assigned owner',{exact:true}).selectOption(ownerId)
    await add.getByLabel('Next action',{exact:true}).fill('Call about weekday mat classes '+width)
    await add.getByLabel('Due at (UTC)',{exact:true}).fill(new Date(Date.now()+86400000).toISOString().slice(0,16))
    await add.getByLabel('Inquiry source (optional)',{exact:true}).fill('Studio open day '+width)
    await add.getByLabel('Inquiry campaign (optional)',{exact:true}).selectOption(campaign.id)
    await shot('capture-source')
    await add.getByRole('button',{name:'Add inquiry',exact:true}).click()
    const added=(await h.state()).pipeline.leads.find(l=>l.source==='Studio open day '+width)
    assert.ok(added)
    assert.equal(added.campaignId,campaign.id)
    await page.locator(`[data-lead-id="${added.id}"] a`).click()
    await page.locator('#lead').getByText('Inquiry source: Studio open day '+width,{exact:true}).waitFor()
    await shot('saved-source')
    await page.goto(h.origin+'/app/leads')
    const campaignForm=page.locator('form[action*="name=lead.campaign.create"]')
    await page.getByText('Record an intro campaign',{exact:true}).click()
    await campaignForm.getByLabel('Campaign name',{exact:true}).fill('Mat open week '+width)
    await campaignForm.getByLabel('Campaign intro offer',{exact:true}).selectOption(intro.id)
    await campaignForm.getByLabel('Campaign starts at (UTC)',{exact:true}).fill(new Date(Date.now()-3600000).toISOString().slice(0,16))
    await campaignForm.getByLabel('Campaign ends at (UTC)',{exact:true}).fill(new Date(Date.now()+86400000).toISOString().slice(0,16))
    await shot('campaign-create')
    await campaignForm.getByRole('button',{name:'Record campaign',exact:true}).click()
    const saved=(await h.state()).leadCampaigns.campaigns.find(c=>c.name==='Mat open week '+width)
    assert.ok(saved)
    const savedRow=page.locator(`[data-funnel-campaign="${saved.id}"]`)
    await savedRow.getByText('Campaign and spending evidence',{exact:true}).click()
    await savedRow.getByLabel('Recorded cost in USD',{exact:true}).fill('12.50')
    await savedRow.getByLabel('Cost occurred at (UTC)',{exact:true}).fill(new Date(Date.now()-60000).toISOString().slice(0,16))
    await savedRow.getByLabel('Spending reference',{exact:true}).fill('synthetic-strap-poster-'+width)
    await shot('cost-create')
    await savedRow.getByRole('button',{name:'Record campaign cost',exact:true}).click()
    await savedRow.locator('[data-campaign-cost]').getByText('$12.50',{exact:true}).waitFor()
    await shot('cost-recorded')
    const tooSmall=await page.locator('main').evaluateAll(els=>els.flatMap(el=>[...el.querySelectorAll('input,select,button,a,p,td,summary')]).filter(el=>el.getClientRects().length&&parseFloat(getComputedStyle(el).fontSize)<13).length)
    assert.equal(tooSmall,0,'readable lead screen text')
    await context.close()
  }}finally{await browser.close()}
}
