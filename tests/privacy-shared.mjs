import assert from 'node:assert/strict'
import {privacyDecision,verifiedPrivacyRequest} from './privacy-journey.mjs'

export async function privacyShared(h) {
  const payer=await h.person('Syntheticfamilypayer'),member=await h.person('Syntheticfamilysubject'),peer=await h.person('Syntheticfamilypeer')
  const waiver=(await h.state()).waiver
  for(const who of [payer,member,peer])await h.cmd('waiver.acknowledge',{id:waiver.id,documentHash:waiver.documentHash,signerName:who.name,confirm:true},who.cookie)
  const home=await h.cmd('household.save',{name:'Synthetic shared household'})
  for(const who of [member,peer])await h.cmd('household.participant.add',{id:home.id,personId:who.id})
  await h.cmd('household.payer.propose',{id:home.id,payerId:payer.id});await h.cmd('household.payer.accept',{id:home.id},payer.cookie)
  const plan=await h.cmd('family.tuition.save',{householdId:home.id,name:'Synthetic family service',service:'Synthetic mobility',startsMonth:'2032-01',endsMonth:'2032-03',discountBps:1000,rows:[{personId:member.id,amountCents:3000,credits:3},{personId:peer.id,amountCents:4000,credits:4}],requestId:'synthetic-strap-family-plan'})
  const preview=await h.cmd('family.bill.preview',{id:plan.id,month:'2032-01',requestId:'synthetic-strap-family-preview'})
  const invoice=await h.cmd('family.bill.accept',{id:preview.id,key:preview.key,confirm:true},payer.cookie)
  const grant=await h.cmd('makeup.guardian.save',{personId:member.id,guardianId:payer.id,relationship:'adult-delegate',authorizationEvidence:'Synthetic explicit delegation'})
  await h.cmd('makeup.guardian.accept',{id:grant.id},member.cookie);await h.cmd('makeup.guardian.accept',{id:grant.id},payer.cookie)
  const access=await verifiedPrivacyRequest(h,member,'access','-shared')
  const bundle=await h.cmd('privacy.export',{id:access.id})
  const ownInvoice=bundle.records.find(r=>r.kind==='familyInvoice').data
  assert.equal(ownInvoice.amountCents,2700);assert.deepEqual(ownInvoice.rows.map(r=>r.personId),[member.id])
  for(const value of [peer.name,peer.email,payer.email,preview.key])assert.ok(!JSON.stringify(bundle).includes(value),'access excludes peer identities and reusable family acceptance keys')
  const request=await verifiedPrivacyRequest(h,member,'erasure','-shared')
  const review=await h.cmd('privacy.erase.prepare',{id:request.id,...privacyDecision})
  await h.cmd('privacy.erase.confirm',{id:review.id,confirm:true})
  const after=await h.state(),retained=after.familyTuition.invoices.find(r=>r.id===invoice.id)
  assert.equal(retained.amountCents,6300,'a participant erasure cannot waive the separate payer obligation')
  assert.equal(after.charges.filter(r=>r.personId===payer.id).reduce((n,r)=>n+r.amountCents,0),6300)
  assert.equal(retained.rows.find(r=>r.personId===peer.id).name,peer.name)
  assert.ok(!JSON.stringify(retained).includes(member.name))
  assert.ok(!JSON.stringify(after.familyTuition).includes(member.name),'shared schedules and accepted evidence lose the erased name')
  const next=await h.cmd('family.bill.preview',{id:plan.id,month:'2032-02',requestId:'synthetic-strap-family-next'})
  assert.deepEqual(next.rows.map(r=>r.personId),[peer.id]);assert.equal(next.amountCents,4000)
  await h.cmd('makeup.guardian.accept',{id:grant.id},payer.cookie,404)
  assert.ok(!JSON.stringify((await h.state(payer.cookie)).makeups).includes(member.name))
  const payerRequest=await verifiedPrivacyRequest(h,payer,'erasure','-payer')
  const payerReview=await h.cmd('privacy.erase.prepare',{id:payerRequest.id,...privacyDecision,obligations:'retain'})
  const receipt=await h.cmd('privacy.erase.confirm',{id:payerReview.id,confirm:true})
  assert.equal(receipt.balanceAfterCents,6300,'explicit retention keeps the existing debt')
  await h.cmd('family.bill.preview',{id:plan.id,month:'2032-02',requestId:'synthetic-strap-family-after-payer'},h.owner,409)
  assert.ok((await h.state()).people.some(p=>p.id===peer.id),'erasing the payer preserves the other participant')

  const duplicate=await h.person('Syntheticmergesource'),target=await h.person('Syntheticmergetarget')
  await h.cmd('member.note.add',{personId:duplicate.id,text:'Synthetic private duplicate history',alert:false})
  const merge=await h.cmd('member.merge.prepare',{sourceId:duplicate.id,targetId:target.id,reason:'Synthetic duplicate history',requestId:'synthetic-strap-merge-preview'})
  await h.cmd('member.merge.confirm',{id:merge.id,key:merge.key,requestId:'synthetic-strap-merge-confirm'})
  const mergedAccess=await verifiedPrivacyRequest(h,target,'access','-merged')
  const mergedBundle=await h.cmd('privacy.export',{id:mergedAccess.id})
  assert.ok(mergedBundle.records.some(r=>r.kind==='memberMerge'))
  for(const value of [duplicate.email,'Synthetic private duplicate history',merge.key])assert.ok(!JSON.stringify(mergedBundle).includes(value),'a history link does not disclose a second identity or confirmation key')
  const erase=await verifiedPrivacyRequest(h,duplicate,'erasure','-merged')
  await h.cmd('privacy.erase.confirm',{id:(await h.cmd('privacy.erase.prepare',{id:erase.id,...privacyDecision})).id,confirm:true})
  const exit=await h.send('/api/strap/exit.json',undefined,h.owner)
  for(const value of [duplicate.name,duplicate.email,'Synthetic private duplicate history'])assert.ok(!exit.text.includes(value),'merged history does not retain erased personal values')
  assert.ok(exit.text.includes(target.name));assert.ok((await h.state()).people.some(p=>p.id===target.id))
}
