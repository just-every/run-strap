import assert from 'node:assert/strict'
import { assertFinanceDownloads } from './finance-downloads.mjs'

/** Corrections, returned tender and unsupported gift changes stay visible in monthly projections. */
export async function financeRestatement(h,{cmd,state,read,jump,buy,key,member,coach,publish,retail,gift}) {
  const sale=await buy({personId:member.id,kind:'credits',credits:2,amountCents:10001,expiresAt:'2032-07-01T07:00:00Z',planName:'Two visits with half-cent value'})
  const first=await publish('2032-05-22T17:00:00Z','Corrected finite service'),second=await publish('2032-06-02T17:00:00Z','Cumulative finite service')
  const bookings=[]
  for(const entry of [first,second]){
    const booking=await cmd('booking.book',{classId:entry.id},member.cookie)
    assert.equal(booking.packId,sale.pack.id);bookings.push(booking)
  }
  await jump('2032-05-23T07:00:00Z')
  await cmd('attendance.noshow',{id:bookings[0].id},coach.cookie)
  const before=await read('2032-05'),beforeRow=before.rows.find(r=>r.id===sale.charge.id)
  assert.deepEqual([beforeRow.earnedCents,beforeRow.deferredCents,beforeRow.consumedBookingIds],[0,10001,[]])
  await cmd('attendance.correct',{id:bookings[0].id,outcome:'attended',reason:'Retained paper attendance confirms personal attendance'})
  const after=await read('2032-05'),afterRow=after.rows.find(r=>r.id===sale.charge.id)
  assert.deepEqual([afterRow.earnedCents,afterRow.deferredCents,afterRow.consumedBookingIds],[5001,5000,[bookings[0].id]],'correction restates completed service with exact half-up cents')
  assert.equal(after.closing.earnedCents,before.closing.earnedCents+5001)
  assert.equal(after.closing.deferredCents,before.closing.deferredCents-5001)
  assert.equal(after.closing.unclassifiedCents,before.closing.unclassifiedCents-700)
  const retained=(await state()).bookings.find(b=>b.id===bookings[0].id)
  assert.equal(retained.corrections.length,1);assert.equal(retained.corrections[0].before.attendance,'no_show')
  const paidBefore=await read('2032-05')
  await cmd('payment.record',{personId:member.id,amountCents:1000000,reference:key()})
  const overpaid=await read('2032-05')
  assert.equal((await state()).balances.find(b=>b.personId===member.id).balanceCents,-989999,'excess external receipt preserves signed member credit')
  assert.ok(overpaid.closing.receivableCents<0,'the consolidated report exposes a negative receivable')
  assert.equal(overpaid.closing.receivableCents,paidBefore.closing.receivableCents-1000000)
  assert.equal(overpaid.closing.cashCents,paidBefore.closing.cashCents+1000000)
  const returned=await cmd('retail.return',{saleId:retail.id,quantity:1,restock:true,reason:'Unused gift-funded mat returned',requestId:key()})
  const returnedReport=await read('2032-05')
  assert.equal(returnedReport.closing.cashCents,overpaid.closing.cashCents,'returned gift tender is not external cash')
  assert.equal(returnedReport.closing.noncashGiftTenderCents,overpaid.closing.noncashGiftTenderCents-2000)
  assert.equal(returnedReport.closing.giftLiabilityCents,overpaid.closing.giftLiabilityCents+2000)
  assert.equal(returnedReport.closing.earnedCents,overpaid.closing.earnedCents-2000)
  assert.equal(returnedReport.closing.receivableCents,overpaid.closing.receivableCents)
  assert.equal(returnedReport.closing.reconciliationDifferenceCents,0)
  const returnCharge=(await state()).charges.find(c=>c.id===returned.chargeId)
  assert.ok(returnCharge,'the public return retains a signed charge')
  assert.deepEqual([returnedReport.rows.find(r=>r.id===returnCharge.id).amountCents,returnedReport.rows.find(r=>r.id===returnCharge.id).earnedCents],[-2000,-2000])
  const adjustment=await cmd('retail.gift.adjust',{giftCardId:gift.id,amountCents:137,reason:'Owner records an unsupported promotional adjustment for review',requestId:key()})
  const adjusted=await read('2032-05')
  assert.equal(adjusted.closing.giftLiabilityCents,returnedReport.closing.giftLiabilityCents+137)
  assert.equal(adjusted.closing.cashCents,returnedReport.closing.cashCents)
  assert.equal(adjusted.closing.reconciliationDifferenceCents,-137,'unsupported gift adjustment remains a visible nonzero difference')
  assert.equal(adjusted.sources.find(s=>s.id===adjustment.id).amountCents,137)
  await assertFinanceDownloads(h,h.owner,adjusted)
  await cmd('attendance.checkin',{id:bookings[1].id},coach.cookie)
  await jump('2032-06-03T07:00:00Z')
  const june=await read('2032-06'),may=await read('2032-05')
  assert.deepEqual(june.opening,may.closing)
  const juneRow=june.rows.find(r=>r.id===sale.charge.id)
  assert.deepEqual([juneRow.earnedCents,juneRow.deferredCents,juneRow.consumedBookingIds],[10001,0,bookings.map(b=>b.id)],'the second half earns only the remaining 5000 cents, never a second independently rounded 5001')
  assert.equal(juneRow.earnedCents-may.rows.find(r=>r.id===sale.charge.id).earnedCents,5000)
  assert.equal(june.closing.reconciliationDifferenceCents,-137)
  await assertFinanceDownloads(h,h.owner,june)
}
